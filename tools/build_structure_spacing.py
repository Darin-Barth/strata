"""Spread structures out 1.5x (Darin, Nov 7, 2026: "structures are spawning way too close to each other").

Structurify's global modifier (config/structurify.json, 1.5) scales the spacing and separation of every structure set
that uses vanilla's random_spread placement or a type Structurify knows (Cataclysm). It does NOT reach placement types
that keep their own grid maths. Tested on one seed (Nov 7): Moog's structures and IDAS came out at exactly the same
spots with the modifier on. Those are the most numerous small surface structures in the pack (Moog's Voyager alone has
116 sets), so this script copies their structure sets into kubejs/data with spacing and separation x1.5 (same IDs, so
the copies replace the mods' own).

Types handled here (the ones Structurify skips):
  moogs_structures:advanced_random_spread  (Moog's Voyager/Nether/End/Ocean/Soaring Structures)
  integrated_api:advanced_random_spread    (IDAS, Integrated Villages and the other Integrated mods)

Usage: python -I tools/build_structure_spacing.py <mods folder with the pack's jars>
Re-run after a Moog's or Integrated update. Applies to newly generated land only.
"""
import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "kubejs" / "data"
FACTOR = 1.5
TYPES = {"moogs_structures:advanced_random_spread", "integrated_api:advanced_random_spread"}
MARK = "_strata_spacing"  # every generated file carries this key, so a re-run can find and replace its own files


def mod_ids(z):
    try:
        toml = z.read("META-INF/neoforge.mods.toml").decode("utf-8", "replace")
    except KeyError:
        return []
    return re.findall(r"""modId\s*=\s*["']([^"']+)["']""", toml)


def scale(placement):
    p = dict(placement)
    spacing = max(2, round(p["spacing"] * FACTOR))
    p["separation"] = min(round(p["separation"] * FACTOR), spacing - 1)
    p["spacing"] = spacing
    return p


def main(mods_dir):
    found = {}
    for jar in sorted(Path(mods_dir).glob("*.jar")):
        try:
            z = zipfile.ZipFile(jar)
        except zipfile.BadZipFile:
            continue
        for name in z.namelist():
            m = re.match(r"data/([^/]+)/worldgen/structure_set/(.+)\.json$", name)
            if not m:
                continue
            try:
                data = json.loads(z.read(name))
            except ValueError:
                continue
            placement = data.get("placement", {})
            if placement.get("type") not in TYPES:
                continue
            ids = mod_ids(z)
            # the mod that owns the namespace if the jar declares it (a jar can bundle a library), else its first mod
            mid = m.group(1) if m.group(1) in ids else (ids[0] if ids else None)
            found[(m.group(1), m.group(2))] = (data, mid, jar.name)

    # remove this script's earlier output, then write the new set
    for old in OUT.glob("*/worldgen/structure_set/**/*.json"):
        try:
            if MARK in json.loads(old.read_text(encoding="utf-8")):
                old.unlink()
        except ValueError:
            pass

    for (ns, path), (data, mid, jar) in sorted(found.items()):
        p = scale(data["placement"])
        if isinstance(p.get("when_replacing"), dict):  # Moog's: the grid it uses when it replaces a vanilla structure
            p["when_replacing"] = scale(p["when_replacing"])
        out = {MARK: f"generated by tools/build_structure_spacing.py from {jar}: spacing and separation x{FACTOR}"}
        if mid:
            out["neoforge:conditions"] = [{"type": "neoforge:mod_loaded", "modid": mid}]
        out.update({k: v for k, v in data.items() if k != "placement"})
        out["placement"] = p
        target = OUT / ns / "worldgen" / "structure_set" / f"{path}.json"
        target.parent.mkdir(parents=True, exist_ok=True)
        # LF: packwiz hashes the bytes, and git checks out LF (.gitattributes)
        target.write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8", newline="\n")
    by_ns = {}
    for ns, _ in found:
        by_ns[ns] = by_ns.get(ns, 0) + 1
    print(f"wrote {len(found)} structure sets: " + ", ".join(f"{k} {v}" for k, v in sorted(by_ns.items())))


if __name__ == "__main__":
    main(sys.argv[1])
